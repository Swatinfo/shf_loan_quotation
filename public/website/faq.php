        </button>
        <div class="faq-a"><div class="faq-a-inner">
          A large portion of our customer base is proprietors, partnerships, LLPs and private
          limited companies. We know how to structure GST returns, bank statements and
          audited financials so the lender sees your true earning capacity rather than the
          ITR figure alone.
        </div></div>
      </div>

      <h3 class="faq-cat-title">Documentation</h3>
      <div class="faq-item">
        <button class="faq-q"><span>What documents will I need to submit?</span>
          <svg class="plus" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 5v14M5 12h14" stroke-linecap="round"/></svg>
        </button>
        <div class="faq-a"><div class="faq-a-inner">
