      <h3 class="faq-cat-title">Eligibility &amp; CIBIL</h3>
      <div class="faq-item">
        <button class="faq-q"><span>My CIBIL score is low. Can SHF still help?</span>
          <svg class="plus" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 5v14M5 12h14" stroke-linecap="round"/></svg>
        </button>
        <div class="faq-a"><div class="faq-a-inner">
          Often, yes. A low score doesn't automatically mean rejection — it means a narrower
          pool of lenders and different terms. We review your full CIBIL report, flag
          reportable errors, suggest quick clean-ups, and shortlist lenders who weigh the
          broader picture (income stability, property value, co-borrower, etc.).
        </div></div>
      </div>
      <div class="faq-item">
        <button class="faq-q"><span>Can I apply jointly with a family member?</span>
          <svg class="plus" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 5v14M5 12h14" stroke-linecap="round"/></svg>
        </button>
        <div class="faq-a"><div class="faq-a-inner">
          Yes. Spouses, parents, adult children and siblings can be added as co-applicants or
          co-borrowers. This usually increases your eligibility and can unlock tax benefits
          for both applicants.
        </div></div>
      </div>
      <div class="faq-item">
        <button class="faq-q"><span>Do you help self-employed and cash-based businesses?</span>
